// data/worries_raw.json 을 읽어:
//   1) 노이즈 토큰(노래·드라마·게임·밈·해몽·상품 등) 포함 → 버림
//   2) 고민/논쟁 신호어(때/법/불안/마음/해야/vs/찬반/딜레마 ...) 없으면 → 버림
// 결과: data/worries_clean.md (카테고리별 정제 목록)
//
// 실행:  node scripts/clean-worries.mjs
// ============================================================================

import { readFileSync, writeFileSync } from "node:fs";

const raw = JSON.parse(readFileSync("data/worries_raw.json", "utf8"));

// ── 노이즈: 이 토큰이 들어가면 고민/논쟁이 아님 (검색 충돌) ───────────────────
const NOISE = [
  // 음악/영상/콘텐츠
  "가사", "노래", "앨범", "드라마", "영화", "웹툰", "만화", "다시보기",
  "나무위키", "위키", "넷플릭스", "티빙", "왓챠", "디즈니", "ost", "ott", "mp3",
  "다운로드", "토렌트", "자막", "시즌", "회차", "결말", "줄거리", "등장인물",
  "출연진", "배우", "감독", "악보", "옥타브", "원곡", "리메이크", "y2k",
  "코드", "데이", "부부", "역사", "갤러리", "꽃말", "세계", "플리", "테스트",
  "뜨거운감자", "김건모", "로이킴", "남궁옥분", "춤을춰", "최악이었다",
  "갤럭시", "s26", "견적", "비교급", "비교우위", "비교과", "프로그램",
  "글귀", "마운자로", "모델", "이론", "중드", "남주", "여주",
  // 게임/밈/웹소설
  "룬워드", "룬 ", "디아", "광공", "광수", "곰탱이", "드립", "빙의", "짤", "밈",
  "반려몽", "썸원", "게임", "공략",
  // 사전/해몽
  "뜻", "해몽", "징조 꿈", "오는 꿈", "유의어", "어원", "사투리", "일본어", "영어로", "한자", "사전",
  // 상품/지명/기타
  "가격", "분양", "모델하우스", "평수", "아파트", "오피스텔", "부동산", "썸네일",
  "캐릭터", "주가", "종목", "호텔", "맛집", "메뉴", "레시피", "후기", "리뷰",
  "쿠폰", "할인", "택배", "시술", "필러", "리프팅", "텀블러", "보온", "주식",
  "코인", "더힐", "써밋", "써마지", "써모스", "프세카", "데이트코스", "노래방",
  "타로", "포스텔러", "자소서", "사주", "표지 공모전", "현대 마법사",
  "카이토", "토우야", "확인서 발급", "우는꿈", "쫓기는 꿈", "죽어 줘",
  "잠수함", "잠수교", "잠수네", "서귀포", "우도잠수", "축제", "뚜벅뚜벅",
  "신청", "지원금", "얼마", "경기도", "이재명", "비혼식", "비혼세", "비혼모",
];
const noiseRe = new RegExp(NOISE.join("|"));

// ── 신호어: 고민(감정) + 논쟁(가치 충돌) 둘 다 인식 ──────────────────────────
const SIGNAL =
  /(때|방법|어떻게|어떡|할까|싶|싫|힘들|불안|후회|마음|이유|극복|해결|대처|관계|스트레스|우울|외로|허무|현타|번아웃|소진|회의감|자존감|미련|집착|연락|재회|헤어|이별|후유증|권태기|회피형|불안형|짝사랑|고백|읽씹|잠수|비교|열등|혐오|무기력|공허|노잼|목표|방황|상처|거절|인정|눈치|퇴사|이직|죽음|두려|위로|회복|모를|식었|차였|해야|vs|찬반|찬성|반대|토론|질문|딜레마|논쟁|윤리|도덕|정당|공정|차별|책임|권리|자유|평등|의무|금지|허용|낫다|맞|옳|선택|포기|돈|결혼|비혼|동거|혼전|아이|부양|효도|독립|부모|간섭|기대|부담|노후|미래|가난|막막|적성|진로|가치관|걱정|AI|ai|인공지능|안락사|사형|낙태|노키즈존|촉법소년|능력주의|기본소득|재택근무|채식|비건|환경|체벌|캔슬)/;

const seen = new Set();
const byCat = {};
let kept = 0;

for (const r of raw.rows) {
  const p = r.phrase;
  if (noiseRe.test(p)) continue;
  if (!SIGNAL.test(p)) continue;
  if (seen.has(p)) continue;
  seen.add(p);
  (byCat[r.category] ??= []).push(p);
  kept++;
}

for (const k of Object.keys(byCat))
  byCat[k].sort((a, b) => a.localeCompare(b, "ko"));

let md = `# 정제된 고민·논쟁 입구 (노이즈 제거)\n\n원본 ${raw.total}개 → 정제 ${kept}개\n\n`;
for (const [cat, list] of Object.entries(byCat)) {
  md += `## ${cat} (${list.length})\n\n`;
  md += list.map((p) => `- ${p}`).join("\n");
  md += "\n\n";
}
writeFileSync("data/worries_clean.md", md);

console.log("===== 정제 완료 =====");
console.log(`원본 ${raw.total} → 정제 ${kept}`);
for (const [cat, list] of Object.entries(byCat))
  console.log(`  ${cat}: ${list.length}`);
console.log("\n파일: data/worries_clean.md");
