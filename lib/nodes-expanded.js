// Expansion layer from collected/search-review candidates.
// Cards stay unverified by default, then move to public content as source checks land.

function draftCard(name, role, stance, view, action, verification = {}) {
  return {
    name,
    role,
    stance,
    view,
    action,
    quote:
      verification.quote ||
      "이 관점은 아직 직접 인용문과 출처 대조가 필요합니다.",
    source: verification.source || `${name} 관련 저작 · 직접 문구 확인 중`,
    verified: verification.verified || false,
  };
}

function draftWorry({ emotion, doors, actions, angles }) {
  return {
    emotion,
    doors,
    cards: angles.map((angle) => draftCard(...angle)),
    actions,
  };
}

function draftDebate({ question, doors, reflect, angles }) {
  return {
    question,
    doors,
    cards: angles.map((angle) => draftCard(...angle)),
    reflect,
  };
}

