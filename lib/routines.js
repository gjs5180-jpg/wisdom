export function allRoutines() {
  return routines;
}

export function getRoutine(slug) {
  return routines.find((routine) => routine.slug === slug) || null;
}

export function allRoutineParams() {
  return routines.map((routine) => ({ slug: routine.slug }));
}

export function routinesForCategory(categorySlug, limit = 2) {
  return routines
    .filter((routine) => routine.categorySlugs.includes(categorySlug))
    .slice(0, limit);
}
